# French puts a no-break space before ? ! : and inside « »: so such a mark never starts a line by itself.
def _typo(value):
    if isinstance(value, str):
        for mark in ("?", "!", ":", ";"):
            value = value.replace(" " + mark, " " + mark)
        return value.replace("« ", "« ").replace(" »", " »")
    if isinstance(value, (list, tuple)):
        return type(value)(_typo(v) for v in value)
    return value

